#!/usr/bin/env node
/**
 * Normalizes the build output for Hostinger.
 *
 * The Hostinger build generates a TanStack Start SPA shell (`_shell.html`) in
 * the client output. That shell contains the bootstrap data required by
 * StartClient/hydrateStart. This script flattens the client output and promotes
 * the shell to `dist/index.html` so static Apache hosting does not show a blank
 * page.
 *
 * Safe to run after either `vite build` or `vite build --outDir dist`.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const dist = path.join(root, "dist");
const distClient = path.join(dist, "client");
const cfPublic = path.join(root, ".output", "public");

function hasAny(dir) {
  return fs.existsSync(dir) && fs.readdirSync(dir).length > 0;
}

// Nitro/Cloudflare layout: flatten dist/client → dist/
if (hasAny(distClient)) {
  const staging = path.join(root, ".hostinger-stage-dist");
  fs.rmSync(staging, { recursive: true, force: true });
  fs.cpSync(distClient, staging, { recursive: true });
  fs.rmSync(dist, { recursive: true, force: true });
  fs.renameSync(staging, dist);
  console.log(`[hostinger-postbuild] flattened dist/client → dist/`);
} else if (hasAny(cfPublic)) {
  fs.rmSync(dist, { recursive: true, force: true });
  fs.cpSync(cfPublic, dist, { recursive: true });
  console.log(`[hostinger-postbuild] copied ${cfPublic} → ${dist}`);
} else {
  console.error("[hostinger-postbuild] No build output to flatten.");
  process.exit(1);
}

// Promote the TanStack SPA shell to index.html. A hand-written index.html is not
// enough for TanStack Start because hydrateStart expects `window.$_TSR` router
// bootstrap data. `_shell.html` is generated by tanstackStart({ spa: ... }).
const indexPath = path.join(dist, "index.html");
const shellCandidates = [path.join(dist, "_shell.html"), path.join(dist, "_shell", "index.html")];
const shellPath = shellCandidates.find((candidate) => fs.existsSync(candidate));

if (shellPath) {
  fs.copyFileSync(shellPath, indexPath);
  console.log(`[hostinger-postbuild] promoted ${path.relative(dist, shellPath)} → index.html`);
} else if (!fs.existsSync(indexPath)) {
  // Locate the client entry chunk (the file Vite normally injects into index.html).
  const assetsDir = path.join(dist, "assets");
  let entry = null;
  if (fs.existsSync(assetsDir)) {
    const files = fs.readdirSync(assetsDir);
    entry =
      files.find((f) => /^client[-.].*\.js$/.test(f)) ||
      files.find((f) => /^entry[-.].*\.js$/.test(f)) ||
      files.find((f) => /^main[-.].*\.js$/.test(f)) ||
      files.find((f) => /^index[-.].*\.js$/.test(f));
  }
  const scriptTag = entry
    ? `<script type="module" src="/assets/${entry}"></script>`
    : "<!-- no client entry chunk detected -->";
  const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <link rel="icon" href="/icon-192.png" />
    <link rel="manifest" href="/manifest.webmanifest" />
    <title>AR Prime Market</title>
  </head>
  <body>
    <div id="root"></div>
    ${scriptTag}
  </body>
</html>
`;
  fs.writeFileSync(indexPath, html);
  console.warn(
    `[hostinger-postbuild] WARNING: _shell.html not found; synthesized fallback index.html (entry=${entry ?? "none"}).`,
  );
}

if (fs.existsSync(indexPath)) {
  const html = fs.readFileSync(indexPath, "utf8");
  if (!html.includes("$_TSR")) {
    console.warn(
      "[hostinger-postbuild] WARNING: index.html has no TanStack bootstrap marker; rebuild with `npm run build:hostinger`.",
    );
  }
}
